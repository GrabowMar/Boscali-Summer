using System;
using BoscaliSummer.Core.Math;

namespace BoscaliSummer.Modules.Weather.Domain
{
    /// <summary>When a control's feature reaches the player (the mockup's availability tags): LIVE now, S5 with tape motion. The tag of the tape console is gone: slice 4b shipped it.</summary>
    internal enum MetAvail : byte { Live, Motion5 }

    /// <summary>How an action lands (spec 9.3): a SMOOTH rebase, a FADE of one set-piece (20 s), a CUT (one atomic hard swap), or no sky change at all.</summary>
    internal enum MetEffect : byte { None, Smooth, Fade, Cut }

    internal enum MetFrontKind : byte { Warm, Cold, Occluded, Squall }

    /// <summary>One cloud layer for the sky-now tiles. <see cref="Present"/> false draws an empty tile.</summary>
    internal struct MetLayer
    {
        public bool Present;
        public string Label;
        public float BaseMetres, Cover;
    }

    /// <summary>A frontal line as a polyline in kilometres (map frame: x east, z north, origin = theater centre). Drawn exactly as given.</summary>
    internal sealed class MetFront
    {
        public const int MaxPoints = 32;
        public MetFrontKind Kind;
        public float Strength;
        public int Count;
        public readonly float[] X = new float[MaxPoints], Z = new float[MaxPoints];
        /// <summary>Minutes until the line reaches the camera at the current tape speed; NaN while it stands still (today) or is unknown.</summary>
        public float EtaMinutes = float.NaN;
        /// <summary>Unit vector the line travels toward (the symbols sit on that side); zero when unknown.</summary>
        public float DirX, DirZ;
    }

    internal struct MetCell { public float X, Z, Radius; public bool Severe; }

    /// <summary>
    /// One set-piece for its cell and the chart. <see cref="Forced"/> is the console latch; <see cref="Present"/> means the sky draws it now (a forced piece, or one the weather generated by itself).
    /// <see cref="Placed"/> is true only for a formation that stands somewhere (a real superstructure with X, Z and a strength): the chart marks and labels only those, so a forced fog bank
    /// (a low layer, nothing placed) is Present but never Placed. <see cref="FadeProgress"/> is 0 while nothing fades and 0-1 during the 20 s fade (filled from slice 5).
    /// </summary>
    internal struct MetSetPiece { public bool Forced, Present, Placed; public float X, Z, Strength, FadeProgress; }

    /// <summary>One of the nine segments of the story (the pips above the strip), filled from the tape.</summary>
    internal struct MetSegment { public bool Present; public string Label; public WeatherRegimeType Class; }

    /// <summary>What holds a stopped tape: the console's HOLD, or the SET SERVER switch. Main cannot tell the two apart (one config entry), so the adapter leaves None until 4b.</summary>
    internal enum MetHeldBy : byte { None, Console, Server }

    internal struct MetOutlookCell { public int Minutes; public WeatherRegimeType Class; public string Code; public float Rain; }

    /// <summary>A coloured span of the strip, in minutes from now (negative = behind the camera).</summary>
    internal struct MetBlock { public float FromMin, ToMin; public WeatherRegimeType Class; public string Label; }

    /// <summary>A tick on the strip: a front (kind).</summary>
    internal struct MetMark { public float AtMin; public MetFrontKind Kind; public string Label; }

    /// <summary>
    /// Everything the Met Office window shows, as plain values, refilled in place at 4 Hz (no allocation per refresh). The window and the
    /// rules read nothing else, so slices 3, 4a, 4b and 5 re-implement only <see cref="IWeatherChartSource"/>, never the window.
    /// Distances are kilometres in the map frame, headings compass degrees, times minutes unless a name says seconds.
    /// </summary>
    internal sealed class MetOfficeModel
    {
        public const int MaxFronts = 4, MaxCells = 12, SetCount = 6, OutlookCount = 6, MaxBlocks = 12, MaxMarks = 6, LayerCount = 3, SegmentCount = 9;

        // Seat and readiness.
        public bool Host, Captured, HasCamera;

        // Sky now.
        public WeatherRegimeType Class;
        public float Cover;
        /// <summary>1-47 when a library sky is pinned, 0 while the class sky of the legacy timeline shows.</summary>
        public int SkyNumber;
        public string SkyName = "", Metar = "";
        /// <summary>High, mid, low.</summary>
        public readonly MetLayer[] Layers = new MetLayer[LayerCount];
        /// <summary>0-46 when pinned, -1 otherwise.</summary>
        public int PinnedSky = -1;

        // Time.
        public bool Running;
        public MetHeldBy HeldBy;
        /// <summary>1-6 on the host; 0 = unknown (a client: its own Pace setting says nothing about the host's, only <see cref="SpeedMps"/> travels).</summary>
        public int Pace;
        public float SpeedMps, WindMps;
        public int WindFromDeg;

        // Story and strip: the tape's segments and markers around the camera. StoryPick is the story the host chose (0-based), -1 while the mission class picks (AUTO).
        public bool HasStory;
        /// <summary>The story's name and the role of the segment under the cursor (for example "PRE-WARM"); empty without a tape.</summary>
        public string StoryName = "", SkyRole = "";
        public int StoryPick = -1;
        public int StoryIndex = -1, StoryCount = WeatherKey.StoryCount;
        public int BlockCount, MarkCount;
        public readonly MetBlock[] Blocks = new MetBlock[MaxBlocks];
        public readonly MetMark[] Marks = new MetMark[MaxMarks];
        public readonly MetSegment[] Segments = new MetSegment[SegmentCount];
        public string StripNote = "";
        /// <summary>The log card's right-hand caption while a change is pending (R10, slice 5); empty = IDLE.</summary>
        public string Pending = "";

        // Synoptic chart.
        public int FrontCount, CellCount;
        public readonly MetFront[] Fronts = NewFronts();
        public readonly MetCell[] Cells = new MetCell[MaxCells];
        public readonly MetSetPiece[] Sets = new MetSetPiece[SetCount];
        public bool HasAnchor;
        /// <summary>Which of HERE (0) or 30 KM AHEAD (1) the host chose while the anchor still stands where that choice put it (the anchor is world-fixed and the camera moves, so the choice is recorded, never recomputed from the camera); -1 when unknown. With no anchor <see cref="MetOfficeText.AnchorChoice"/> reads DEFAULT.</summary>
        public int AnchorMark = -1;
        public float AnchorX, AnchorZ, CamX, CamZ, CamHeadingDeg, HalfXKm, HalfZKm;

        // Rain, outlook, identity, clocks.
        public float? ForcedRain;
        public bool OutlookHeld;
        public bool HasOutlook;
        public readonly MetOutlookCell[] Outlook = new MetOutlookCell[OutlookCount];
        public string SeedMode = "", SeedHex = "", TapeHex = "", SerialHex = "";
        public int LayoutSalt;
        public float MissionSeconds;
        /// <summary>The host-side event log, newest first, joined with newlines. Empty on a client.</summary>
        public string LogText = "";

        private static MetFront[] NewFronts()
        {
            var fronts = new MetFront[MaxFronts];
            for (int i = 0; i < fronts.Length; i++) fronts[i] = new MetFront();
            return fronts;
        }

        /// <summary>Back to the empty state, keeping every array, so a refill never allocates.</summary>
        public void Reset()
        {
            Host = Captured = HasCamera = false;
            Class = WeatherRegimeType.Clear; Cover = 0f; SkyNumber = 0; SkyName = Metar = ""; PinnedSky = -1;
            Array.Clear(Layers, 0, Layers.Length);
            Running = false; HeldBy = MetHeldBy.None; Pace = TapePace.DefaultPace; SpeedMps = WindMps = 0f; WindFromDeg = 0;
            HasStory = false; StoryName = SkyRole = ""; StoryIndex = -1; StoryPick = -1; StoryCount = WeatherKey.StoryCount;
            BlockCount = MarkCount = 0; StripNote = Pending = "";
            Array.Clear(Segments, 0, Segments.Length);
            FrontCount = CellCount = 0;
            Array.Clear(Sets, 0, Sets.Length);
            HasAnchor = false; AnchorMark = -1; AnchorX = AnchorZ = CamX = CamZ = CamHeadingDeg = HalfXKm = HalfZKm = 0f;
            ForcedRain = null; HasOutlook = OutlookHeld = false;
            Array.Clear(Outlook, 0, Outlook.Length);
            SeedMode = SeedHex = TapeHex = SerialHex = ""; LayoutSalt = 0; MissionSeconds = 0f; LogText = "";
        }

        private static float Fin(float v) => Scalar.IsFinite(v) ? v : 0f;
        private static float Unit(float v) => Scalar.IsFinite(v) ? Scalar.Clamp01(v) : 0f;

        /// <summary>
        /// Makes every number the chart, the barb or a text draws finite: NaN and infinity become 0, covers and strengths are clamped to 0-1, a non-finite rain override is dropped.
        /// A front's <see cref="MetFront.EtaMinutes"/> is left alone (NaN means STATIC). The adapter calls it at the end of Fill; <see cref="MetChartMath"/> is non-finite safe as well.
        /// </summary>
        public void Sanitize()
        {
            Cover = Unit(Cover); SpeedMps = Fin(SpeedMps); WindMps = Fin(WindMps); MissionSeconds = Fin(MissionSeconds);
            CamX = Fin(CamX); CamZ = Fin(CamZ); CamHeadingDeg = Fin(CamHeadingDeg); AnchorX = Fin(AnchorX); AnchorZ = Fin(AnchorZ); HalfXKm = Fin(HalfXKm); HalfZKm = Fin(HalfZKm);
            if (ForcedRain.HasValue && !Scalar.IsFinite(ForcedRain.Value)) ForcedRain = null;
            for (int i = 0; i < Layers.Length; i++) { Layers[i].Cover = Unit(Layers[i].Cover); Layers[i].BaseMetres = Fin(Layers[i].BaseMetres); }
            for (int i = 0; i < Blocks.Length; i++) { Blocks[i].FromMin = Fin(Blocks[i].FromMin); Blocks[i].ToMin = Fin(Blocks[i].ToMin); }
            for (int i = 0; i < Marks.Length; i++) Marks[i].AtMin = Fin(Marks[i].AtMin);
            for (int i = 0; i < Fronts.Length; i++)
            {
                MetFront f = Fronts[i];
                f.Strength = Unit(f.Strength); f.DirX = Fin(f.DirX); f.DirZ = Fin(f.DirZ);
                for (int p = 0; p < MetFront.MaxPoints; p++) { f.X[p] = Fin(f.X[p]); f.Z[p] = Fin(f.Z[p]); }
            }
            for (int i = 0; i < Cells.Length; i++) { Cells[i].X = Fin(Cells[i].X); Cells[i].Z = Fin(Cells[i].Z); Cells[i].Radius = Fin(Cells[i].Radius); }
            for (int i = 0; i < Sets.Length; i++) { Sets[i].X = Fin(Sets[i].X); Sets[i].Z = Fin(Sets[i].Z); Sets[i].Strength = Unit(Sets[i].Strength); Sets[i].FadeProgress = Unit(Sets[i].FadeProgress); }
            for (int i = 0; i < Outlook.Length; i++) Outlook[i].Rain = Unit(Outlook[i].Rain);
        }
    }

    /// <summary>The one read seam of the window. Today it is implemented from what main has; later slices replace the adapter, not the window.</summary>
    internal interface IWeatherChartSource
    {
        /// <summary>Overwrites <paramref name="into"/> with the world as it is now. Never throws; an unready world fills Host/Captured false.</summary>
        void Fill(MetOfficeModel into);
    }

    /// <summary>The one write seam of the window. Every method is one host request; a client or an unready world refuses it (false) and changes nothing.</summary>
    internal interface IMetOfficeCommands
    {
        bool SetTapeMoves(bool moves);
        bool SetPace(int pace);
        /// <summary>0-46 pins that library sky; -1 unpins and resumes the changing weather.</summary>
        bool PinSky(int sky);
        bool Reroll();
        bool SetSets(byte mask);
        bool PlaceAhead(float metres);
        bool ClearPlacement();
        bool SetRain(float? intensity);
        bool Scenario(WeatherScenario scenario);
        /// <summary>Repeats story <paramref name="story"/> (0-based) for the whole tape; -1 hands the choice back to the mission class. A cut: the tape is placed again like a capture.</summary>
        bool SetStory(int story);
        /// <summary>Seam stub (S5): brings the next front to the camera in <paramref name="minutes"/>. The adapter refuses it until tape motion lands.</summary>
        bool FrontIn(int minutes);
    }
}
