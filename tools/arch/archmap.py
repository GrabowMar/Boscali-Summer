def stats(repo, m):
    return {
        "owners": len(repo.owner_list),
        "modules": len(m["modules"]),
        "cs_files": len(repo.cs),
        "cs_lines": sum(fd.lines for fd in repo.cs.values()),
        "contracts_interfaces": len(m["contracts"]["interfaces"]),
        "harmony_entries": len(m["harmony"]),
        "harmony_resolved_targets": len({e["target"] for e in m["harmony"] if e["target"] != "dynamic"}),
        "harmony_dynamic": sum(1 for e in m["harmony"] if e["target"] == "dynamic"),
        "harmony_shared_targets": len(m["shared"]),
        "settings_keys": len(m["binds"]),
        "settings_sections": len({b["section"] for b in m["binds"]}),
        "client_settings": len(m["client"]),
        "host_settings": len(m["host"]),
        "net_messages": len(m["messages"]),
        "protocol_constants": len(m["protocols"]),
        "sim_hooks": len(m["hooks"]),
        "pinned_files": None if m["pinned"] is None else len(m["pinned"]["pinned"]),
        "pinned_types": None if m["pinned"] is None else len(m["pinned"]["type_refs"]),
        "unbalanced_brace_files": sorted(fd.path for fd in repo.cs.values() if fd.unbalanced),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description="Map the mod architecture into markdown and guard module boundaries.")
    ap.add_argument("--write", action="store_true", help="regenerate docs/generated/*.md and MODULE.md blocks")
    ap.add_argument("--check", action="store_true", help="exit 1 if generated docs are stale or a rule/ratchet fails")
    ap.add_argument("--update-baseline", action="store_true", help="rewrite tools/arch/baseline.json from current numbers")
    ap.add_argument("--stats", action="store_true", help="print headline counts as JSON")
    args = ap.parse_args(argv)
    if not (args.write or args.check or args.update_baseline or args.stats):
        ap.print_help()
        return 2
    repo = Repo(REPO)
    m = build_model(repo)
    code_ = 0
    if args.update_baseline:
        data = current_numbers(repo, m)
        data = {"_note": "Ratchet baseline for tools/arch/archmap.py --check; regenerate with --update-baseline.", **data}
        write_file(BASELINE, json.dumps(data, indent=2, sort_keys=True) + "\n")
        print("wrote " + BASELINE)
    if args.write:
        out = all_outputs(repo, m)
        changed = 0
        for rel, content in sorted(out.items()):
            full = os.path.join(REPO, rel)
            if not os.path.isfile(full) or read_text(full) != content:
                write_file(rel, content)
                changed += 1
        print("archmap: %d files checked, %d written%s" % (len(out), changed,
              "" if m["pinned"] is not None else " (nomodkit not found: PINNED.md left untouched)"))
    if args.check:
        failures, hints = check(repo, m)
        for h in hints:
            print("hint: " + h)
        if failures:
            print("archmap --check FAILED (%d):" % len(failures))
            for f in failures:
                print("  - " + f)
            code_ = 1
        else:
            print("archmap --check passed.")
    if args.stats:
        print(json.dumps(stats(repo, m), indent=2, sort_keys=True))
    return code_


if __name__ == "__main__":
    sys.exit(main())
