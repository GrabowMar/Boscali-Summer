def load_baseline():
    path = os.path.join(REPO, BASELINE)
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8-sig") as f:
        return json.load(f)


def check(repo, m):
    failures, hints = [], []
    out = all_outputs(repo, m)
    stale = []
    for rel, content in sorted(out.items()):
        full = os.path.join(REPO, rel)
        if not os.path.isfile(full) or read_text(full) != content:
            stale.append(rel)
    if stale:
        failures.append("Generated docs are stale (%d): %s%s\n    fix: python tools/arch/archmap.py --write" % (
            len(stale), ", ".join(stale[:8]), " …" if len(stale) > 8 else ""))
    if m["pinned"] is None:
        hints.append("nomodkit not found (set NOMODKIT_ROOT or place it at ../nomodkit): PINNED.md left as is, not checked.")
    base = load_baseline()
    cur = current_numbers(repo, m)
    if base is None:
        failures.append("Missing %s.\n    fix: python tools/arch/archmap.py --update-baseline" % BASELINE)
        return failures, hints
    # R1
    b1 = base.get("r1_cross_module_namespace_refs", {})
    for owner, n in cur["r1_cross_module_namespace_refs"].items():
        if n > b1.get(owner, 0):
            refs = sorted(m["r1"][owner])
            failures.append("R1 modules/%s references other modules' namespaces (%d > baseline %d): %s\n"
                            "    fix: go through a Core/Contracts interface + ModuleServices.TryGet instead." % (
                                owner, n, b1.get(owner, 0), "; ".join("%s -> BoscaliSummer.Modules.%s" % r for r in refs[:6])))
    for owner, n in b1.items():
        if cur["r1_cross_module_namespace_refs"].get(owner, 0) < n:
            hints.append("R1 improved for %s; run --update-baseline." % owner)
    # R2
    allowed = set(base.get("r2_core_files_allowed_to_reference_modules", []))
    for p in cur["r2_core_files_allowed_to_reference_modules"]:
        if p not in allowed:
            failures.append("R2 %s references BoscaliSummer.Modules.{%s}; Core must not depend on modules.\n"
                            "    fix: move the dependency behind a Core/Contracts interface (or, if this is the composition root, "
                            "add it to the baseline allowlist deliberately)." % (p, ",".join(sorted(m["r2"][p]))))
    if allowed - set(cur["r2_core_files_allowed_to_reference_modules"]):
        hints.append("R2 allowlist has files that no longer reference modules; run --update-baseline.")
    # ratchets
    for key, label, fix in (
            ("global_state_reads", "Plugin.Settings/Plugin.Logger reads", "take settings/logger from ModuleContext"),
            ("namespace_prefix_mismatches", "namespace declarations outside the owner prefix", "use the owner's namespace for new files"),
            ("shared_harmony_targets", "Harmony targets shared with another owner", "extend the existing patch or expose a hook")):
        bv = base.get(key, {})
        for owner, n in cur[key].items():
            if n > bv.get(owner, 0):
                detail = ""
                if key == "namespace_prefix_mismatches":
                    detail = ": " + "; ".join("%s (%s)" % x for x in sorted(m["nsmis"][owner])[:4])
                elif key == "shared_harmony_targets":
                    detail = ": " + ", ".join(t for t, os_ in sorted(m["shared"].items()) if owner in os_)
                failures.append("Ratchet %s grew for %s (%d > baseline %d)%s\n    fix: %s." % (label, owner, n, bv.get(owner, 0), detail, fix))
        for owner, n in bv.items():
            if cur[key].get(owner, 0) < n:
                hints.append("%s improved for %s (%d -> %d); run --update-baseline." % (label, owner, n, cur[key].get(owner, 0)))
    bl = base.get("large_files", {})
    if cur["large_files"]["count"] > bl.get("count", 0):
        new = [p for p in cur["large_files"]["files"] if p not in bl.get("files", [])]
        failures.append("Ratchet: .cs files over %d lines grew (%d > baseline %d); new: %s\n    fix: split the file "
                        "(partial class) without renaming types." % (LARGE_FILE_LINES, cur["large_files"]["count"],
                                                                     bl.get("count", 0), ", ".join(new) or "-"))
    elif cur["large_files"]["count"] < bl.get("count", 0):
        hints.append("Large files dropped (%d -> %d); run --update-baseline." % (bl.get("count", 0), cur["large_files"]["count"]))
    return failures, hints


