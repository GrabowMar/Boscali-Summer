def read_text(path):
    with open(path, encoding="utf-8-sig", errors="replace", newline="") as f:
        return f.read().replace("\r\n", "\n").replace("\r", "\n")


def read_many(root, paths):
    """Read many files concurrently (opening files dominates on Windows); results in input order."""
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=8) as pool:
        return list(pool.map(lambda p: read_text(os.path.join(root, p)), paths))


def list_files(root):
    """Tracked plus untracked-but-not-ignored files (posix paths), else a filtered walk."""
    try:
        out = subprocess.run(
            ["git", "-C", root, "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True, check=True, timeout=60).stdout
        files = {p for p in out.decode("utf-8", "replace").split("\0") if p}
        return sorted(f for f in files if os.path.isfile(os.path.join(root, f)))
    except (OSError, subprocess.SubprocessError):
        found = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            rel = os.path.relpath(dirpath, root).replace(os.sep, "/")
            for name in filenames:
                found.append(name if rel == "." else rel + "/" + name)
        return sorted(found)


def owner_of(path):
    parts = path.split("/")
    if parts[0] == "modules" and len(parts) > 2:
        return parts[1]
    if parts[0] in TOP_OWNERS and len(parts) > 1:
        return parts[0]
    return None


def owner_folder(owner):
    return owner if owner in TOP_OWNERS else "modules/" + owner


def glob_regex(pattern):
    p = pattern.strip().replace("\\", "/")
    while p.startswith("./"):
        p = p[2:]
    out, i = "", 0
    while i < len(p):
        if p.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif p.startswith("**", i):
            out += ".*"
            i += 2
        elif p[i] == "*":
            out += "[^/]*"
            i += 1
        elif p[i] == "?":
            out += "[^/]"
            i += 1
        else:
            out += re.escape(p[i])
            i += 1
    return re.compile(out + r"\Z", re.I)


# --------------------------------------------------------------------------- C# masking

TOKEN_RE = re.compile(r'''
    (?P<lc>//[^\n]*)
  | (?P<bc>/\*.*?\*/)
  | (?P<raw>\$*"""[^\n]*?"""|\$*"""\n.*?\n[ \t]*""")
  | (?P<vs>(?:\$@|@\$|@)"(?:[^"]|"")*")
  | (?P<istr>\$+"(?:[^"\\\n]|\\.)*")
  | (?P<s>"(?:[^"\\\n]|\\.)*")
  | (?P<c>'(?:[^'\\\n]|\\.){1,10}')
''', re.S | re.X)
DIRECTIVE_RE = re.compile(r"^[ \t]*#[^\n]*", re.M)


def blank(s):
    return " " * len(s) if "\n" not in s else "\n".join(" " * len(x) for x in s.split("\n"))


def unescape(s):
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), s)


class FileData:
    """One C# file: original text, a same-length masked copy (comments/strings blanked), structure."""

    def __init__(self, path, text, owner):
        self.path, self.text, self.owner = path, text, owner
        self.lines = text.count("\n") + (0 if text.endswith("\n") or not text else 1)
        self.strings = []      # (pos, value) of plain/verbatim string literals
        self.directives = []   # (pos, directive text)
        masked = TOKEN_RE.sub(self._mask, text)
        if "#" in masked:
            parts, last = [], 0
            for m in DIRECTIVE_RE.finditer(text):
                hash_pos = text.index("#", m.start())
                if masked[hash_pos] != "#":
                    continue  # inside a comment or string
                self.directives.append((m.start(), m.group(0).strip()))
                parts.append(masked[last:m.start()])
                parts.append(" " * (m.end() - m.start()))
                last = m.end()
            parts.append(masked[last:])
            masked = "".join(parts)
        self.masked = masked
        self._braces()
        self._preprocessor()
        self.namespaces = []   # (name, start, end, decl_pos)
        for m in re.finditer(r"\bnamespace\s+([\w.]+)\s*([{;])", self.masked):
            o = m.start(2)
            end = self.match.get(o, len(self.masked)) if m.group(2) == "{" else len(self.masked)
            self.namespaces.append((m.group(1), o, end, m.start()))
        self.types = []
        self.release_excluded = False

    def _mask(self, m):
        kind, s = m.lastgroup, m.group(0)
        if kind in ("lc", "bc"):
            return blank(s)
        if kind == "c":
            return "'" + " " * (len(s) - 2) + "'"
        q = s.index('"')
        if kind == "raw":
            q = len(s) - len(s.lstrip("$"))
            return s[:q + 3] + blank(s[q + 3:-3]) + '"""'
        body = s[q + 1:-1]
        if kind == "s":
            self.strings.append((m.start(), unescape(body)))
        elif kind == "vs":
            self.strings.append((m.start(), body.replace('""', '"')))
        return s[:q + 1] + blank(body) + '"'

    def _braces(self):
        stack, self.match = [], {}
        for m in re.finditer(r"[{}]", self.masked):
            if m.group() == "{":
                stack.append(m.start())
            elif stack:
                self.match[stack.pop()] = m.start()
        self.unbalanced = len(stack)
        self.opens = sorted(self.match)

    def _preprocessor(self):
        self.dev_spans, self.release_spans, stack = [], [], []
        end_of_file = len(self.text)

        def close(frame, pos):
            cond = frame["cur"]
            if re.search(r"!\s*PUBLIC_RELEASE\b", cond) and "||" not in cond:
                self.dev_spans.append((frame["start"], pos))
            elif re.search(r"(?<![!\w])PUBLIC_RELEASE\b", cond) and "||" not in cond:
                self.release_spans.append((frame["start"], pos))

        for pos, d in self.directives:
            m = re.match(r"#\s*(if|elif|else|endif)\b(.*)", d)
            if not m:
                continue
            kw, cond = m.group(1), m.group(2).split("//")[0].strip()
            if kw == "if":
                stack.append({"cond": cond, "cur": cond, "start": pos})
            elif stack and kw == "elif":
                close(stack[-1], pos)
                stack[-1].update(cur=cond, start=pos)
            elif stack and kw == "else":
                close(stack[-1], pos)
                c = stack[-1]["cond"]
                neg = c[1:].strip() if c.startswith("!") else "!" + c
                stack[-1].update(cur=neg, start=pos)
            elif stack and kw == "endif":
                close(stack.pop(), pos)
        for frame in stack:
            close(frame, end_of_file)

    def dev_only(self, pos):
        return self.release_excluded or any(a <= pos < b for a, b in self.dev_spans)

    def namespace_at(self, pos):
        best = None
        for name, o, e, _ in self.namespaces:
            if o <= pos <= e and (best is None or o > best[1]):
                best = (name, o)
        return best[0] if best else ""

    def segments(self, o, c):
        """Spans inside (o, c) that are not inside a nested brace block."""
        segs, i = [], o + 1
        k = bisect.bisect_right(self.opens, o)
        while k < len(self.opens) and self.opens[k] < c:
            b = self.opens[k]
            if b >= i:
                segs.append((i, b))
                i = self.match[b] + 1
            k += 1
        segs.append((i, c))
        return segs


# --------------------------------------------------------------------------- small parsers

PAIRS = {"(": ")", "[": "]", "{": "}"}


def match_close(s, i, limit=None):
    """Index of the bracket closing s[i] (one of ([{), counting all three kinds; -1 if none."""
    depth, n = 0, len(s) if limit is None else limit
    while i < n:
        ch = s[i]
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return -1


def split_top(fd, a, b):
    """Split text[a:b] at depth-0 commas of the masked copy; returns stripped original slices."""
    out, depth, start, M = [], 0, a, fd.masked
    for i in range(a, b):
        ch = M[i]
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "," and depth == 0:
            out.append(fd.text[start:i].strip())
            start = i + 1
    tail = fd.text[start:b].strip()
    if tail or out:
        out.append(tail)
    return out


def call_args(fd, open_paren):
    close = match_close(fd.masked, open_paren)
    if close < 0:
        return []
    return split_top(fd, open_paren + 1, close)


def simple_type(t):
    t = t.strip().replace("global::", "")
    t = re.sub(r"<.*>", "", t)
    return t.split(".")[-1].strip()


def last_seg(t):
    return t.strip().split(".")[-1].strip()


def const_string(fd, name, pos=None):
    best = None
    for m in re.finditer(r"\bconst\s+string\s+" + re.escape(name) + r'\s*=\s*"((?:[^"\\]|\\.)*)"', fd.text):
        if pos is None or m.start() <= pos or best is None:
            best = unescape(m.group(1))
    return best


def literal_value(fd, arg, pos=None):
    """A string literal, nameof(x), or a const string identifier; None if not static."""
    a = arg.strip()
    m = re.fullmatch(r'@?"((?:[^"\\]|\\.)*)"', a)
    if m:
        return unescape(m.group(1))
    m = re.fullmatch(r"nameof\(\s*([\w.]+)\s*\)", a)
    if m:
        return last_seg(m.group(1))
    m = re.fullmatch(r"(?:[\w.]+\.)?([A-Za-z_]\w*)", a)
    if m:
        return const_string(fd, m.group(1), pos)
    return None


def preamble_start(M, pos):
    depth, i = 0, pos - 1
    while i >= 0:
        ch = M[i]
        if ch == "]":
            depth += 1
        elif ch == "[":
            depth -= 1
        elif depth == 0 and ch in ";{}":
            return i + 1
        i -= 1
    return 0


def attr_lists(fd, a, b):
    """[...] attribute lists fully inside [a, b): yields (open, close)."""
    M, i = fd.masked, a
    while True:
        o = M.find("[", i, b)
        if o < 0:
            return
        c = match_close(M, o, b)
        if c < 0:
            return
        yield o, c
        i = c + 1


def attr_items(fd, o, c):
    """Items of one attribute list: (name, args or None, pos)."""
    items = []
    for part_start, part in _split_positions(fd, o + 1, c):
        m = re.match(r"\s*(?:\w+\s*:\s*)?([\w.]+)\s*(\()?", fd.masked[part_start:part_start + len(part) + 1])
        if not m:
            continue
        name = last_seg(m.group(1))
        args = None
        if m.group(2):
            args = call_args(fd, part_start + m.start(2))
        items.append((name, args, part_start))
    return items


def _split_positions(fd, a, b):
    out, depth, start, M = [], 0, a, fd.masked
    for i in range(a, b):
        ch = M[i]
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "," and depth == 0:
            out.append((start, fd.text[start:i]))
            start = i + 1
    out.append((start, fd.text[start:b]))
    return out


MODIFIERS = r"(?:public|private|protected|internal|static|sealed|abstract|partial|readonly|unsafe|new|ref|file|virtual|override|extern)"
NEXT_TYPE_RE = re.compile(r"(?:\s*\[[^\]]*\])*\s*(?:" + MODIFIERS + r"\s+)*(class|struct|interface|enum|record)\b")
NEXT_MEMBER_RE = re.compile(r"(?:\s*\[[^\]]*\])*\s*(?:" + MODIFIERS + r"\s+)*[\w.<>\[\],?]+\s+(\w+)\s*\(")
DELEGATE_RE = re.compile(r"\bdelegate\s+(?:[\w.<>\[\],?]+\s+)+?([A-Za-z_]\w*)\s*(?:<[^<>()]*>)?\s*\(")
TYPE_RE = re.compile(r"\b(class|struct|interface|enum|record(?:\s+class|\s+struct)?)\s+([A-Za-z_]\w*)")


class TypeDecl:
    __slots__ = ("name", "kind", "ns", "outer", "fd", "start", "open", "close", "bases", "attrs", "display", "full")

    def segments(self):
        if self.open is None or self.close is None:
            return []
        return self.fd.segments(self.open, self.close)


def parse_types(fd):
    M, n, types = fd.masked, len(fd.masked), []
    for m in TYPE_RE.finditer(M):
        if m.start() > 0 and M[m.start() - 1] in ".@":
            continue
        j = m.end()
        while j < n and M[j] in " \t\n":
            j += 1
        if j < n and M[j] == "<":
            depth = 0
            while j < n:
                if M[j] == "<":
                    depth += 1
                elif M[j] == ">":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            j += 1
            while j < n and M[j] in " \t\n":
                j += 1
        if j >= n or not (M[j] in "{:(;" or M.startswith("where", j)):
            continue
        k, depth = j, 0
        while k < n:
            ch = M[k]
            if ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1
            elif depth == 0 and ch in "{;":
                break
            k += 1
        t = TypeDecl()
        t.name, t.kind, t.fd, t.start = m.group(2), m.group(1).split()[0], fd, m.start()
        t.ns = fd.namespace_at(m.start())
        header = fd.text[m.end():k]
        t.bases = []
        hm = re.search(r"(?:\)|>|^|\s):\s*(.*?)(?:\bwhere\b|$)", header, re.S) if ":" in fd.masked[m.end():k] else None
        if hm:
            t.bases = [simple_type(b) for b in split_top_text(hm.group(1)) if b.strip()]
        if k < n and M[k] == "{":
            t.open, t.close = k, fd.match.get(k)
        else:
            t.open = t.close = None
        pre = preamble_start(M, m.start())
        t.attrs = []
        for o, c in attr_lists(fd, pre, m.start()):
            t.attrs.extend(attr_items(fd, o, c))
        types.append(t)
    for m in DELEGATE_RE.finditer(M):
        t = TypeDecl()
        t.name, t.kind, t.fd, t.start = m.group(1), "delegate", fd, m.start()
        t.ns, t.bases, t.open, t.close = fd.namespace_at(m.start()), [], None, None
        t.attrs = []
        types.append(t)
    types.sort(key=lambda t: t.start)
    stack = []
    for t in types:
        while stack and (stack[-1].close is None or stack[-1].close < t.start):
            stack.pop()
        t.outer = stack[-1] if stack else None
        if t.open is not None and t.close is not None:
            stack.append(t)
    for t in types:
        chain, o = [t.name], t.outer
        while o is not None:
            chain.append(o.name)
            o = o.outer
        chain.reverse()
        t.display = ".".join(chain)
        t.full = (t.ns + "." if t.ns else "") + "+".join(chain)
    return types


def split_top_text(s):
    out, depth, start = [], 0, 0
    for i, ch in enumerate(s):
        if ch in "(<[{":
            depth += 1
        elif ch in ")>]}":
            depth -= 1
        elif ch == "," and depth == 0:
            out.append(s[start:i])
            start = i + 1
    out.append(s[start:])
    return [x.strip() for x in out]


def innermost_type(fd, pos):
    best = None
    for t in fd.types:
        if t.open is not None and t.close is not None and t.open < pos < t.close:
            if best is None or t.open > best.open:
                best = t
    return best


def member_body(t, name):
    """(start, end) of the body of member `name(...)` declared directly in type t, else None."""
    fd, M = t.fd, t.fd.masked
    for a, b in t.segments():
        for m in re.finditer(r"\b" + re.escape(name) + r"\s*(?:<[^<>()]*>)?\s*\(", M[a:b]):
            s = a + m.start()
            if re.search(r"\bnew\s*$", M[max(0, s - 8):s]):
                continue
            close = match_close(M, a + m.end() - 1)
            if close < 0:
                continue
            j = close + 1
            while j < len(M) and M[j] in " \t\n":
                j += 1
            if M.startswith("=>", j):
                k, depth = j + 2, 0
                while k < len(M):
                    ch = M[k]
                    if ch in "([{":
                        depth += 1
                    elif ch in ")]}":
                        depth -= 1
                    elif ch == ";" and depth == 0:
                        break
                    k += 1
                return j + 2, k
            if j < len(M) and M[j] == "{" and j in fd.match:
                return j + 1, fd.match[j]
    return None


