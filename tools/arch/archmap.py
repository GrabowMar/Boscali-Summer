class Repo:
    def __init__(self, root):
        self.root = root
        self.files = list_files(root)
        self.cs = {}
        self.owners = {o for o in map(owner_of, self.files) if o}
        sources = [p for p in self.files if p.endswith(".cs") and owner_of(p)]
        for p, text in zip(sources, read_many(root, sources)):
            self.cs[p] = FileData(p, text, owner_of(p))
        mods = sorted(o for o in self.owners if o not in TOP_OWNERS)
        self.owner_list = [o for o in TOP_OWNERS if o in self.owners] + mods
        self._compile_rules()
        for fd in self.cs.values():
            fd.release_excluded = not self.compiled(fd.path, "release")
            fd.types = parse_types(fd)
        self.types = [t for fd in self.cs.values() for t in fd.types]
        self.types_by_name = defaultdict(list)
        for t in self.types:
            self.types_by_name[t.name].append(t)
        self.declared_ns = set()
        for fd in self.cs.values():
            for name, *_ in fd.namespaces:
                self.declared_ns.add(name)

    # csproj ------------------------------------------------------------------
    def _compile_rules(self):
        self.rules = []
        projs = [p for p in self.files if p.endswith(".csproj") and "/" not in p]
        self.csproj = projs[0] if projs else None
        default_items = True
        if self.csproj:
            text = re.sub(r"<!--.*?-->", "", read_text(os.path.join(self.root, self.csproj)), flags=re.S)
            if re.search(r"<EnableDefault(?:Compile)?Items>\s*false", text, re.I):
                default_items = False
            for g in re.finditer(r"<ItemGroup\b([^>]*)>(.*?)</ItemGroup>", text, re.S):
                cond = re.search(r'Condition="([^"]*)"', g.group(1))
                cfg = "both"
                if cond:
                    c = cond.group(1).replace(" ", "")
                    if "'$(PublicRelease)'=='true'" in c:
                        cfg = "release"
                    elif "'$(PublicRelease)'!='true'" in c:
                        cfg = "dev"
                for it in re.finditer(r'<Compile\s+(Include|Remove)="([^"]*)"(?:\s+Exclude="([^"]*)")?', g.group(2)):
                    excl = [glob_regex(x) for x in (it.group(3) or "").split(";") if x.strip()]
                    for pat in it.group(2).split(";"):
                        if pat.strip():
                            self.rules.append((cfg, it.group(1), glob_regex(pat), excl, pat.strip()))
        if default_items:
            self.rules.insert(0, ("both", "Include", glob_regex("**/*.cs"), [glob_regex("bin/**"), glob_regex("obj/**")], "**/*.cs"))

    def compiled(self, path, cfg):
        inc = False
        for rcfg, op, rx, excl, _ in self.rules:
            if rcfg not in ("both", cfg):
                continue
            if op == "Include" and rx.match(path) and not any(e.match(path) for e in excl):
                inc = True
            elif op == "Remove" and rx.match(path):
                inc = False
        return inc

    def release_removes(self):
        return sorted(p for cfg, op, _, _, p in self.rules if cfg == "release" and op == "Remove")

    def dev_includes(self):
        return sorted(p for cfg, op, _, _, p in self.rules if cfg == "dev" and op == "Include")

    def owner_files(self, owner):
        return [fd for p, fd in sorted(self.cs.items()) if fd.owner == owner]


