#!/usr/bin/env python3
"""Build modules/Hud/Domain/Scope/StoreArtBounds.Generated.cs: the ink bounding box of every vanilla weapon and countermeasure picture.

The game keeps one Sprite per weapon (WeaponInfo.weaponIcon) and per countermeasure (Countermeasure.displayImage): thin line art on a wide empty
canvas (a slim missile fills 11-30 % of the sprite's height), and the texture cannot be read at run time, so the TAC BOARD cannot find the art by
looking at pixels. This script reads the extracted pictures once (the PNGs of the "png_mask" folder: alpha is ink; and map.json, which says which
weapon wears which picture) and writes a switch keyed by the sprite's name that returns the box the art lives in, as fractions of the sprite
(left, top, right, bottom; y down). The board draws only that part of the sprite (a RawImage's uvRect) so the art fills its box.

    py -I tools/Build-StoreArtBounds.py <png_mask folder> <map.json> [out.cs]

Needs Pillow. The extraction itself (UnityPy over the game's .assets files) is not part of the repository; the generated table is.
"""
import argparse
import json
import os
import sys

from PIL import Image

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DEFAULT_OUT = os.path.join(REPO, "modules", "Hud", "Domain", "Scope", "StoreArtBounds.Generated.cs")
INK = 40   # alpha above this is ink (the dim glow around a stroke is not)


def bounds(path):
    """(left, top, right, bottom) in pixels of the ink of one picture (right and bottom exclusive), the picture's width and height."""
    with Image.open(path) as im:
        alpha = im.convert("RGBA").getchannel("A")
        box = alpha.point(lambda v: 255 if v > INK else 0).getbbox()
        return box, im.width, im.height


def weapons(map_json):
    """sprite file stem -> the first weapon (or countermeasure) name that wears it, from the extraction's map."""
    names = {}
    for row in json.load(open(map_json, encoding="utf-8")):
        label = (row.get("strings") or [row.get("asset") or ""])[0]
        for f in row.get("files", []):
            names.setdefault(os.path.splitext(f)[0], label)
    return names


def emit(rows, out):
    lines = [
        "// <auto-generated>",
        "// Generated by tools/Build-StoreArtBounds.py from the extracted vanilla weapon pictures (alpha above %d is ink). Do not edit; rerun the script." % INK,
        "// </auto-generated>",
        "namespace BoscaliSummer.Modules.Hud.Domain",
        "{",
        "    internal static partial class StoreArtBounds",
        "    {",
        "        /// <summary>The box the art of the vanilla sprite named <paramref name=\"sprite\"/> lives in, as fractions of the sprite; false for a sprite the table does not know (a modded weapon's: its whole sprite is used).</summary>",
        "        public static bool TryGet(string sprite, out ArtBounds bounds)",
        "        {",
        "            switch (sprite)",
        "            {",
    ]
    for name, (x0, y0, x1, y1), label in rows:
        lines.append('                case "%s": bounds = new ArtBounds(%sf, %sf, %sf, %sf); return true;      // %s' % (name, x0, y0, x1, y1, label))
    lines += [
        "                default: bounds = default; return false;",
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("pictures", help="folder of the extracted pictures (png_mask: white, alpha = ink)")
    ap.add_argument("map", help="map.json of the extraction")
    ap.add_argument("out", nargs="?", default=DEFAULT_OUT)
    args = ap.parse_args()

    labels = weapons(args.map)
    stems = sorted(os.path.splitext(f)[0] for f in os.listdir(args.pictures) if f.lower().endswith(".png"))
    missing = sorted(set(labels) - set(stems))
    if missing:
        sys.exit("map.json names pictures that are not in the folder: " + ", ".join(missing))
    rows = []
    for stem in stems:
        box, w, h = bounds(os.path.join(args.pictures, stem + ".png"))
        if box is None:
            print("no ink in %s: left out (the whole sprite is used)" % stem)
            continue
        l, t, r, b = box
        rows.append((stem, ("%.4f" % (l / w), "%.4f" % (t / h), "%.4f" % (r / w), "%.4f" % (b / h)), labels.get(stem, "")))
        print("%-36s %4dx%-4d ink %3d %3d %3d %3d  (%.0f%% x %.0f%%)" % (stem, w, h, l, t, r, b, 100 * (r - l) / w, 100 * (b - t) / h))
    emit(rows, args.out)
    print("%d pictures -> %s" % (len(rows), os.path.relpath(args.out, REPO)))


if __name__ == "__main__":
    main()
